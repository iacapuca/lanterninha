// Writes db/demo/seed.sql: fictional reviews (and their reviewers) on real
// ANCINE rooms in well-known venues, so the site isn't empty. Run after the
// ANCINE import; idempotent (INSERT OR IGNORE). Demo users have no credentials.
import { writeFileSync } from 'node:fs'
import type { Criterion, Tag } from '../../src/lib/domain.ts'
import { TAGS } from '../../src/lib/domain.ts'
import { assignIds, fold, loadOpenComplexes } from '../ancine/parse.ts'
import { BODIES, FILMS, USERNAMES } from './content.ts'

/** Venues to showcase, matched by ANCINE's complex name and city. */
const SHOWCASE: Array<[string, string]> = [
  ['CINEMARK ELDORADO', 'SAO PAULO'],
  ['UCI ANALIA FRANCO', 'SAO PAULO'],
  ['ESPACO ITAU DE CINEMA AUGUSTA', 'SAO PAULO'],
  ['BELAS ARTES', 'SAO PAULO'],
  ['CINESESC', 'SAO PAULO'],
  ['CINESYSTEM POMPEIA', 'SAO PAULO'],
  ['ODEON', 'RIO DE JANEIRO'],
  ['UCI NEW YORK', 'RIO DE JANEIRO'],
  ['CINE BELAS ARTES', 'BELO HORIZONTE'],
  ['CINE BRASILIA', 'BRASILIA'],
  ['CINEMA SAO LUIZ', 'RECIFE'],
  ['UCI SHOPPING CENTER RECIFE', 'RECIFE'],
  ['CINEMATECA CAPITOLIO', 'PORTO ALEGRE'],
  ['CINE PASSEIO', 'CURITIBA'],
  ['IMAX PALLADIUM', 'CURITIBA'],
  ['UCI ORIENT SHOPPING DA BAHIA', 'SALVADOR'],
  ['CINEPOLIS RIOMAR', 'FORTALEZA'],
  ['KINOPLEX DOM PEDRO', 'CAMPINAS'],
]

function mulberry32(seed: number) {
  return () => {
    seed |= 0
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const rand = mulberry32(20261014)
const pick = <T>(xs: readonly T[]) => xs[Math.floor(rand() * xs.length)]!
const clamp = (n: number, min: number, max: number) => Math.min(max, Math.max(min, n))
const q = (v: unknown) =>
  v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`
const saoPauloDay = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Sao_Paulo' })

const complexes = assignIds(loadOpenComplexes())
const showcase = SHOWCASE.map(([name, city]) => {
  const match = complexes.find((c) => fold(c.city) === city && fold(c.name).includes(name))
  if (!match) console.warn(`not found: ${name} (${city})`)
  return match
}).filter((c) => c != null)

const lines = ['-- Generated by db/demo/generate.ts. Fictional reviews on real ANCINE rooms.']
const now = Date.UTC(2026, 9, 1)
for (const u of USERNAMES) {
  lines.push(
    `INSERT OR IGNORE INTO user (id, name, email, email_verified, username, display_username, created_at, updated_at) VALUES (${[
      `seed_${u}`,
      u,
      `${u}@demo.lanterninha.invalid`,
      0,
      u,
      u,
      now,
      now,
    ]
      .map(q)
      .join(', ')});`,
  )
}

const start = Date.UTC(2025, 0, 1)
const end = Date.UTC(2026, 9, 10)
let reviews = 0
for (const cinema of showcase) {
  // Up to three rooms per venue, special formats first.
  const rooms = [...cinema.rooms].sort((a, b) => Number(b.format != null) - Number(a.format != null)).slice(0, 3)
  for (const room of rooms) {
    const quality = 2.8 + rand() * 2 + (room.format ? 0.3 : 0)
    const authors = new Set<string>()
    const attempts = 4 + Math.floor(rand() * 10)
    for (let i = 0; i < attempts; i++) {
      const username = pick(USERNAMES)
      if (authors.has(username)) continue
      authors.add(username)

      const noise = () => (rand() - 0.5) * 1.6
      const rating = clamp(Math.round((quality + noise()) * 2) / 2, 0.5, 5)
      const criterion = (bias: number) => clamp(Math.round(quality + bias + noise()), 1, 5)
      const criteria: Record<Criterion, number> = {
        picture: criterion(room.format === 'imax' ? 0.4 : 0),
        sound: criterion(room.format === 'imax' ? 0.4 : 0),
        comfort: criterion(room.format === 'vip' || room.format === 'prime' ? 0.6 : -0.2),
        cleanliness: criterion(0),
      }
      const tags = new Set<Tag>()
      for (let t = Math.floor(rand() * 3); t > 0; t--) tags.add(pick(TAGS))
      const createdAt = Math.round(start + rand() * (end - start))
      const band = rating >= 4 ? 'high' : rating >= 2.5 ? 'mid' : 'low'

      lines.push(
        `INSERT OR IGNORE INTO review (id, room_id, user_id, rating, picture, sound, comfort, cleanliness, row, film, body, tags, day, created_at) VALUES (${[
          `demo-${room.id}-${username}`,
          room.id,
          `seed_${username}`,
          rating,
          criteria.picture,
          criteria.sound,
          criteria.comfort,
          criteria.cleanliness,
          rand() > 0.3 ? String.fromCharCode(67 + Math.floor(rand() * 11)) : null,
          rand() > 0.15 ? pick(FILMS) : null,
          pick(BODIES[band]),
          JSON.stringify([...tags]),
          saoPauloDay.format(new Date(createdAt)),
          createdAt,
        ]
          .map(q)
          .join(', ')});`,
      )
      reviews++
    }
  }
}

writeFileSync('db/demo/seed.sql', lines.join('\n') + '\n')
console.log(`db/demo/seed.sql: ${USERNAMES.length} users, ${reviews} reviews across ${showcase.length} venues`)

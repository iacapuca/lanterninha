// Builds db/ancine/import.sql: upserts every open ANCINE complex and room into
// D1, keyed by ANCINE registration numbers. Re-runnable after each monthly
// `pnpm ancine:download`. Community-voted formats survive re-imports; rooms and
// cinemas that closed are removed unless they already have reviews.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { assignIds, fold, loadOpenComplexes } from './parse.ts'
import { findMunicipality } from '../geo/municipalities.ts'

const OUT = 'db/ancine/import.sql'
const geocoded: Record<string, { lat: number; lng: number } | null> = existsSync('db/geo/geocode-cache.json')
  ? JSON.parse(readFileSync('db/geo/geocode-cache.json', 'utf8'))
  : {}

const q = (v: unknown) =>
  v == null ? 'NULL' : typeof v === 'number' || typeof v === 'boolean' ? String(Number(v)) : `'${String(v).replace(/'/g, "''")}'`

const complexes = assignIds(loadOpenComplexes())
const lines: string[] = ['-- Generated by db/ancine/import.ts from ANCINE open data (CC BY). Do not edit.']
let precise = 0
let approximate = 0

for (const c of complexes) {
  const hit = geocoded[c.ancineId]
  const city = findMunicipality(c.city, c.state)
  const [lat, lng, precision] = hit ? [hit.lat, hit.lng, 'address'] : city ? [city.lat, city.lng, 'city'] : [null, null, null]
  if (hit) precise++
  else if (city) approximate++

  lines.push(
    `INSERT INTO cinema (id, ancine_id, name, chain, city, state, neighborhood, address, cep, website, lat, lng, geo_precision) VALUES (${[
      c.id, c.ancineId, c.name, c.chain, c.city, c.state, c.neighborhood, c.address, c.cep, c.website, lat, lng, precision,
    ].map(q).join(', ')}) ON CONFLICT(ancine_id) DO UPDATE SET name = excluded.name, chain = excluded.chain, city = excluded.city, state = excluded.state, neighborhood = excluded.neighborhood, address = excluded.address, cep = excluded.cep, website = excluded.website, lat = excluded.lat, lng = excluded.lng, geo_precision = excluded.geo_precision;`,
  )

  for (const r of c.rooms) {
    const searchText = fold(`${r.name} ${c.name} ${c.chain} ${c.neighborhood} ${c.city}`).toLowerCase()
    lines.push(
      `INSERT INTO room (id, ancine_id, cinema_id, name, format, format_source, seats, wheelchair_seats, reduced_mobility_seats, large_seats, accessible_restroom, accessible, search_text) VALUES (${[
        r.id, r.ancineId,
      ].map(q).join(', ')}, (SELECT id FROM cinema WHERE ancine_id = ${q(c.ancineId)}), ${[
        r.name, r.format, r.format ? 'ancine' : null, r.seats, r.wheelchairSeats, r.reducedMobilitySeats,
        r.largeSeats, r.accessibleRestroom, r.accessible, searchText,
      ].map(q).join(', ')}) ON CONFLICT(ancine_id) DO UPDATE SET cinema_id = excluded.cinema_id, name = excluded.name, seats = excluded.seats, wheelchair_seats = excluded.wheelchair_seats, reduced_mobility_seats = excluded.reduced_mobility_seats, large_seats = excluded.large_seats, accessible_restroom = excluded.accessible_restroom, accessible = excluded.accessible, search_text = excluded.search_text, format = CASE WHEN room.format_source = 'community' THEN room.format ELSE excluded.format END, format_source = CASE WHEN room.format_source = 'community' THEN room.format_source ELSE excluded.format_source END;`,
    )
  }
}

// Closed since the last import: drop them unless people already reviewed them.
const openRooms = complexes.flatMap((c) => c.rooms.map((r) => q(r.ancineId))).join(', ')
const openComplexes = complexes.map((c) => q(c.ancineId)).join(', ')
lines.push(
  `DELETE FROM room WHERE ancine_id IS NOT NULL AND ancine_id NOT IN (${openRooms}) AND id NOT IN (SELECT room_id FROM review);`,
  `DELETE FROM cinema WHERE ancine_id IS NOT NULL AND ancine_id NOT IN (${openComplexes}) AND id NOT IN (SELECT cinema_id FROM room);`,
)

writeFileSync(OUT, lines.join('\n') + '\n')
const rooms = complexes.reduce((n, c) => n + c.rooms.length, 0)
console.log(`${OUT}: ${complexes.length} cinemas (${precise} geocoded by address, ${approximate} by city), ${rooms} rooms`)

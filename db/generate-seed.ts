// Writes db/seed.sql from the demo data in seed-data.ts. Idempotent
// (INSERT OR IGNORE), so it is safe to run against a database that already has it.
import { writeFileSync } from 'node:fs'
import { CINEMAS, ROOMS, SEED_REVIEWS } from './seed-data.ts'

const q = (v: unknown) =>
  v == null ? 'NULL' : typeof v === 'number' || typeof v === 'boolean' ? String(Number(v)) : `'${String(v).replace(/'/g, "''")}'`
const insert = (table: string, rows: Record<string, unknown>[]) =>
  rows.map((r) => `INSERT OR IGNORE INTO ${table} (${Object.keys(r).join(', ')}) VALUES (${Object.values(r).map(q).join(', ')});`)
const fold = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
const saoPauloDay = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Sao_Paulo' })

const cinemasById = new Map(CINEMAS.map((c) => [c.id, c]))
const usernames = [...new Set(SEED_REVIEWS.map((r) => r.username))].sort()
const now = Date.UTC(2026, 9, 1)

const lines = [
  '-- Generated by db/generate-seed.ts. Demo data: real venues, fictional reviews.',
  // Seed users have no `account` row, so nobody can sign in as them.
  ...insert('user', usernames.map((u) => ({
    id: `seed_${u}`, name: u, email: `${u}@demo.lanterninha.invalid`, email_verified: 0,
    username: u, display_username: u, created_at: now, updated_at: now,
  }))),
  ...insert('cinema', CINEMAS.map((c) => ({
    id: c.id, name: c.name, chain: c.chain, city: c.city, state: c.state,
    neighborhood: c.neighborhood, address: c.address, lat: c.lat, lng: c.lng,
  }))),
  ...insert('room', ROOMS.map((r) => {
    const c = cinemasById.get(r.cinemaId)!
    return {
      id: r.id, cinema_id: r.cinemaId, name: r.name, format: r.format, seats: r.seats,
      projection: r.projection, sound: r.sound, accessible: r.accessible,
      search_text: fold(`${r.name} ${c.name} ${c.chain} ${c.neighborhood} ${c.city}`),
    }
  })),
  ...insert('review', SEED_REVIEWS.map((r) => ({
    id: r.id, room_id: r.roomId, user_id: `seed_${r.username}`, rating: r.rating,
    picture: r.criteria.picture, sound: r.criteria.sound, comfort: r.criteria.comfort,
    cleanliness: r.criteria.cleanliness, row: r.row, film: r.film, body: r.body,
    tags: JSON.stringify(r.tags), day: saoPauloDay.format(new Date(r.createdAt)),
    created_at: Date.parse(r.createdAt),
  }))),
]
writeFileSync('db/seed.sql', lines.join('\n') + '\n')
console.log(`db/seed.sql: ${usernames.length} users, ${CINEMAS.length} cinemas, ${ROOMS.length} rooms, ${SEED_REVIEWS.length} reviews`)
